/* ===========================================================================
   login-prompt.ts —— session 过期时弹出的「重新登录」框（§4.7 / §3.10）
   ---------------------------------------------------------------------------
   为什么要有这个模块：401 是一个**横切事实**——任何一次请求都可能撞上
   （`http.ts` 文件头）。撞上的那一刻用户正在做一件事：扫设备列表、在会话里
   敲终端、填新建会话表单填了一半。旧的处置是 `location.assign('/login')`：
   一次整页跳转把在做的事连同地址栏一起丢掉，用户回来还得自己导航回去，
   而重新登录本来只需要一个密码。

   于是这里只做一件事：记住「框该开着」。输对密码 → 关掉框、原地继续；
   取消 → 那一下才真的离开（见 `App.vue` 的 `onLoginCancel`）。

   ── 为什么状态在模块里，而不是 App.vue 的一个 ref ──────────────────
   `http.ts` 是一个普通模块，不是组件：它没有地方放组件状态，也不该为了
   触发一个框去 import `App.vue`（那会成环）。模块级 ref 与 `router.ts` 的
   `route` 是同一条路子——「一个不是组件的模块需要广播状态」时的做法。

   ── 布尔值而不是计数器 ──────────────────────────────────────────
   并发请求会连着撞见好几个 401（设备页一次就打两个端点）。用计数会弹出两个
   框、而且少关一个就永远关不掉；布尔值天然幂等——第二次 `promptLogin()`
   什么也不做，用户眼前仍然只有一个框。

   ── 「取消」不在这里 ────────────────────────────────────────────
   本模块只管「框开著」。取消是**离开当前页面**这个动作，它住在 `App.vue`：
   主动登出走 `onLogout`（先 `POST /logout` 再换页），取消走 `onLoginCancel`
   （只换页）。拆开的收益是 `lib/` 里不会再出现第二个会整页跳转的地方——
   要找「哪里有跳转」时只消看外壳。
   =========================================================================== */

import { ref } from 'vue'

/** 重新登录框开着吗。由 `http.ts` 的 401 分支置位，由 `App.vue` 复位。 */
export const loginPromptOpen = ref(false)

/**
 * 打开重新登录框。
 *
 * 幂等（见文件头）：连撞多个 401 时不会叠出第二个框。
 */
export function promptLogin(): void {
  loginPromptOpen.value = true
}

/** 关掉它（登录成功、或换了个动作之后）。 */
export function dismissLoginPrompt(): void {
  loginPromptOpen.value = false
}
