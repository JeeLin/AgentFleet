/* ===========================================================================
   files-path.ts —— 文件面板的路径判据（页面与面板共用一份）
   ---------------------------------------------------------------------------
   越界判据与 cwd 相对路径**只能有一份**：页面（`SessionPage`）与面板
   （`FilesPanel`）各写一份时，两份会漂——漂出来的差异是「同一个路径在一处
   判越界、在另一处不判」，用户看到的是自相矛盾的界面。
   =========================================================================== */

/**
 * 层名 / 条目名里的越界写法。
 *
 * 真判据在 node 侧（`resolve_within`），这里**不是**第二份边界检查——它只
 * 负责把已经判出来的边界**画出来**（§7.4 ①②）。字符串判据只认两种明写在
 * 路径里的逃逸：`..` 与绝对路径。符号链接逃逸不看名字，所以链接行的越界
 * 由宿主在 `error` 里给。
 */
export function isOutsideSeg(seg: string): boolean {
  return seg === '..' || seg.startsWith('/')
}

/** 当前目录的相对路径（每层一个数组项，空段不算一层）。 */
export function cwdPathOf(cwd: readonly string[]): string {
  return cwd.filter((s) => s.length > 0).join('/')
}
