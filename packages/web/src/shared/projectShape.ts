/* ===========================================================================
   项目形态（shape）的中文名 —— 全仓唯一一份
   ---------------------------------------------------------------------------
   三种形态的名字出自 `PRODUCT.md` §3.2 的表格，**不另造说法**。此前这四个
   文件各写一份（总览页的常量表、看板菜单与项目设置页的两个同签名函数
   `describeShape()`、新建项目页的内联对象），改一个产品用词要同时动四处，
   而漏掉的那一处会让同一块板子上出现「中心式」与「Central」两种叫法。

   这里只放**名字**。每页对形态的其它解释（「代码从哪来、到哪去」「Hub 上存
   什么」）各不相同，那些留在各自的页面里——把它们也塞进来，就变成了一份
   谁都不敢改的大表。

   `shape` 是**开放字符串**（后端 `ProjectSummary.shape` 没有闭集类型，见
   `domains/device/api.ts` 顶部），所以查不到时必须回落原文：显示 `weird`
   比显示空白好排查，也不会因为后端加了第四种形态就让页面看起来坏了。
   =========================================================================== */

/** 已知形态的中文名。查不到时用 `describeShape()` 回落原文。 */
export const SHAPE_LABELS: Readonly<Record<string, string>> = {
  central: '中心式',
  mirror: '镜像式',
  isolated: '隔离式',
}

/** 把 `shape` 翻成人话；未知形态原样返回。 */
export function describeShape(shape: string): string {
  return SHAPE_LABELS[shape] ?? shape
}
